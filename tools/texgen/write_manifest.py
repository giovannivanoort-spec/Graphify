"""Write the MaterialIds.luau manifest from the upload results.

usage:
  python -I write_manifest.py <uploads.json> <means.json> <out MaterialIds.luau> [--strict]

uploads.json maps each uploaded file to its asset id, e.g.
  { "http://127.0.0.1:47823/tex/Pavers_color.png": "rbxassetid://123", ... }
(any URL or path works: only the file name after the last / is used; bare
numeric ids are accepted too). means.json is the one gen_textures.py wrote.

The manifest keeps the AI Asphalt entry verbatim (copied from the existing
<out MaterialIds.luau> when it has one, else the known ids), points HonedStone's colour
and normal at PolishedTile's maps, gives every carpet the shared Carpet_normal /
Carpet_rough maps, writes metalness "" for everything except Brass, and lists
the loose images under Images. Missing uploads are written as "" (the variant
is then skipped by Materials.ensure) and listed on stderr; --strict makes them
an error instead.
"""
import json
import re
import sys
from urllib.parse import unquote

HEADER = """--!strict
-- MaterialIds.luau — GENERATED by tools/texgen/write_manifest.py; don't edit by
-- hand. Uploaded image IDs per material key, plus the measured mean (0-255) of
-- each colour map, which Materials.tint uses to hit WorldPalette targets.
return {
"""

# the AI-generated asphalt, kept exactly as it was
ASPHALT = """\tAsphalt = {
\t\tcolor = "rbxassetid://81648168569586", normal = "rbxassetid://91889000708535",
\t\troughness = "rbxassetid://132591565018310", metalness = "rbxassetid://124790536031644",
\t\tmean = { 84, 80, 83 },
\t},
"""

# Materials.Defs order
MATERIALS = ["Pavers", "PlazaTile", "ConcreteSlab", "SmoothConcrete", "Stucco", "Ashlar",
             "RoofMembrane", "Brass", "PolishedTile", "HonedStone", "Hedge"]
CARPETS = ["CarpetCrimson", "CarpetRoyal", "CarpetEmerald", "CarpetBlackGold",
           "CarpetMidnight", "CarpetNeon", "CarpetChips", "CarpetRetro"]
IMAGES = [("ParkingStalls", "ParkingStalls.png"), ("Zebra", "Zebra.png"),
          ("TowerWarmColor", "TowerWarm_color.png"), ("TowerWarmEmit", "TowerWarm_emit.png"),
          ("TowerCoolColor", "TowerCool_color.png"), ("TowerCoolEmit", "TowerCool_emit.png"),
          # night colour maps (lit cells baked in) for the emissive CM_TowerX variants
          ("TowerWarmNightColor", "TowerWarm_night.png"), ("TowerCoolNightColor", "TowerCool_night.png"),
          ("UvTest", "UvTest.png")]

ID_RE = re.compile(r"rbxassetid://\d+")
ASPHALT_RE = re.compile(r"^\tAsphalt = \{\n.*?^\t\},\n", re.S | re.M)


def existing_asphalt(path):
    """the Asphalt block of the manifest being replaced, verbatim (None if absent)"""
    try:
        with open(path, encoding="utf-8-sig") as f:
            text = f.read().replace("\r\n", "\n")
    except OSError:
        return None
    m = ASPHALT_RE.search(text)
    return m.group(0) if m and ID_RE.search(m.group(0)) else None


def load_uploads(path):
    with open(path, encoding="utf-8-sig") as f:
        raw = json.load(f)
    ids, bad = {}, []
    for key, val in raw.items():
        name = unquote(re.split(r"[\\/]", key.split("?")[0].rstrip("/\\"))[-1])
        if isinstance(val, dict):
            val = val.get("assetUri") or val.get("uri") or val.get("assetId") or val.get("id") or ""
        val = str(val).strip()
        if val.isdigit():
            val = "rbxassetid://" + val
        if not ID_RE.fullmatch(val):
            bad.append(f"{name}: {val!r}")
            continue
        ids[name.lower()] = val
    return ids, bad


def fmt_mean(m):
    return ", ".join(str(int(round(v))) if abs(v - round(v)) < 1e-6 else f"{v:.1f}" for v in m)


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    strict = "--strict" in sys.argv[1:]
    if len(args) != 3:
        sys.exit(__doc__)
    uploads_path, means_path, out_path = args
    ids, bad = load_uploads(uploads_path)
    with open(means_path, encoding="utf-8-sig") as f:
        means = json.load(f)
    missing = []

    def asset(fname):
        v = ids.get(fname.lower())
        if v is None:
            missing.append(fname)
            return ""
        return v

    def entry(key, color, normal, rough, metal, mean):
        lines = [f"\t{key} = {{",
                 f'\t\tcolor = "{color}", normal = "{normal}",',
                 f'\t\troughness = "{rough}", metalness = "{metal}",']
        if mean is not None:
            lines.append(f"\t\tmean = {{ {fmt_mean(mean)} }},")
        else:
            missing.append(f"mean of {key}")
        lines.append("\t},")
        return "\n".join(lines) + "\n"

    body = [HEADER, existing_asphalt(out_path) or ASPHALT]
    for key in MATERIALS:
        if key == "HonedStone":    # PolishedTile's colour + normal, its own (matte) roughness
            body.append(entry(key, asset("PolishedTile_color.png"), asset("PolishedTile_normal.png"),
                              asset("HonedStone_rough.png"), "",
                              means.get("HonedStone") or means.get("PolishedTile")))
            continue
        metal = asset("Brass_metal.png") if key == "Brass" else ""
        body.append(entry(key, asset(f"{key}_color.png"), asset(f"{key}_normal.png"),
                          asset(f"{key}_rough.png"), metal, means.get(key)))
    body.append("\t-- casino carpets: colour baked in, one shared flat-ish normal + roughness\n")
    normal, rough = asset("Carpet_normal.png"), asset("Carpet_rough.png")
    for key in CARPETS:
        body.append(entry(key, asset(f"{key}_color.png"), normal, rough, "", means.get(key)))
    body.append("\t-- loose images (Materials.Images)\n\tImages = {\n")
    for name, fname in IMAGES:
        body.append(f'\t\t{name} = "{asset(fname)}",\n')
    body.append("\t},\n}\n")

    text = "".join(body)
    assert text.count("{") == text.count("}"), "unbalanced braces"
    if strict and (missing or bad):
        sys.exit("not written: missing " + ", ".join(sorted(set(missing))) +
                 ("; bad ids " + ", ".join(bad) if bad else ""))
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {out_path}: {len(MATERIALS) + 1 + len(CARPETS)} materials, {len(IMAGES)} images")
    if bad:
        print("ignored (not an rbxassetid): " + ", ".join(bad), file=sys.stderr)
    if missing:
        print("MISSING (written as \"\"): " + ", ".join(sorted(set(missing))), file=sys.stderr)


if __name__ == "__main__":
    main()
